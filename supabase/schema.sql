-- Run this in Supabase Dashboard > SQL Editor before migrating the local SQLite data.
-- RLS is enabled with no client-facing policies: the Flask server uses the database
-- connection credentials, and the publishable key is intentionally not used here.

CREATE TABLE IF NOT EXISTS public.professors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    university TEXT DEFAULT '',
    role TEXT DEFAULT '',
    department TEXT DEFAULT '',
    research TEXT DEFAULT '',
    alignment TEXT DEFAULT '',
    score INTEGER DEFAULT 0,
    tier TEXT DEFAULT '',
    verification TEXT DEFAULT '',
    source TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    stage TEXT DEFAULT 'Not contacted',
    followup_days INTEGER NOT NULL DEFAULT 7,
    created_at TEXT NOT NULL,
    photo_url TEXT DEFAULT '',
    status TEXT DEFAULT 'Identified',
    state TEXT DEFAULT '',
    category TEXT DEFAULT 'None',
    my_notes TEXT DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS professors_email_lower_uidx ON public.professors (lower(email));

CREATE TABLE IF NOT EXISTS public.drafts (
    professor_id BIGINT PRIMARY KEY REFERENCES public.professors(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.outbound (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES public.professors(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    sent_at TEXT NOT NULL,
    graph_id TEXT,
    conversation_id TEXT,
    kind TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS outbound_professor_sent_idx ON public.outbound (professor_id, sent_at DESC);

CREATE TABLE IF NOT EXISTS public.inbound (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES public.professors(id) ON DELETE CASCADE,
    graph_id TEXT NOT NULL UNIQUE,
    conversation_id TEXT,
    subject TEXT,
    received_at TEXT,
    from_email TEXT,
    preview TEXT,
    match_type TEXT NOT NULL,
    flagged_response INTEGER NOT NULL DEFAULT 0,
    body TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS inbound_professor_received_idx ON public.inbound (professor_id, received_at DESC);

CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

ALTER TABLE public.professors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.outbound ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inbound ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
