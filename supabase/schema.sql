-- Run this in Supabase Dashboard > SQL Editor before migrating the local SQLite data.
-- RLS is enabled with no client-facing policies: the Flask server uses the database
-- connection credentials, and the publishable key is intentionally not used here.

CREATE TABLE IF NOT EXISTS public.professors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    university TEXT DEFAULT '',
    role TEXT DEFAULT '',
    department TEXT DEFAULT '',
    research TEXT DEFAULT '',
    alignment TEXT DEFAULT '',
    score INTEGER DEFAULT 0,
    tier TEXT DEFAULT '',
    verification TEXT DEFAULT '',
    source TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    stage TEXT DEFAULT 'Not contacted',
    followup_days INTEGER NOT NULL DEFAULT 7,
    created_at TEXT NOT NULL,
    photo_url TEXT DEFAULT '',
    status TEXT DEFAULT 'Identified',
    state TEXT DEFAULT '',
    category TEXT DEFAULT 'None',
    my_notes TEXT DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS professors_email_lower_uidx ON public.professors (lower(email));

CREATE TABLE IF NOT EXISTS public.drafts (
    professor_id BIGINT PRIMARY KEY REFERENCES public.professors(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.outbound (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES public.professors(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    sent_at TEXT NOT NULL,
    graph_id TEXT,
    conversation_id TEXT,
    kind TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS outbound_professor_sent_idx ON public.outbound (professor_id, sent_at DESC);

CREATE TABLE IF NOT EXISTS public.inbound (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES public.professors(id) ON DELETE CASCADE,
    graph_id TEXT NOT NULL UNIQUE,
    conversation_id TEXT,
    subject TEXT,
    received_at TEXT,
    from_email TEXT,
    preview TEXT,
    match_type TEXT NOT NULL,
    flagged_response INTEGER NOT NULL DEFAULT 0,
    body TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS inbound_professor_received_idx ON public.inbound (professor_id, received_at DESC);

CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.main_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_spreadsheet_id TEXT NOT NULL,
    source_sheet_name TEXT NOT NULL DEFAULT 'MainEvents',
    source_row INTEGER NOT NULL CHECK (source_row >= 2),
    category TEXT,
    event_type TEXT,
    event_name TEXT,
    event_start DATE,
    event_end DATE,
    status TEXT,
    next_action TEXT,
    location_format TEXT,
    om_grade TEXT,
    event_notes TEXT,
    event_contact_info TEXT,
    location_url TEXT,
    sheet_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_spreadsheet_id, source_sheet_name, source_row)
);
CREATE INDEX IF NOT EXISTS main_events_dates_idx ON public.main_events (event_start, event_end);
CREATE INDEX IF NOT EXISTS main_events_name_idx ON public.main_events (lower(event_name));
SELECT setval(pg_get_serial_sequence('public.main_events', 'id'),
              COALESCE((SELECT MAX(id) FROM public.main_events), 1),
              EXISTS (SELECT 1 FROM public.main_events));

ALTER TABLE public.professors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.outbound ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inbound ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.main_events ENABLE ROW LEVEL SECURITY;

-- Normalized event catalog. Keep main_events intact as the historical source table.
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL UNIQUE,
    event_class TEXT NOT NULL,
    sub_category TEXT,
    original_category TEXT,
    event_type TEXT,
    event_status TEXT NOT NULL DEFAULT 'Active',
    event_contact_info TEXT,
    best_known_start_date TEXT,
    best_known_end_date TEXT,
    best_known_start_time TIME,
    best_known_end_time TIME,
    location_format TEXT,
    location_url TEXT,
    event_notes TEXT,
    image_url TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.events ADD COLUMN IF NOT EXISTS image_url TEXT;
-- Master-event date estimates may be seasons or phrases such as "Spring 2027".
-- Preserve existing ISO dates as text, while occurrence dates remain DATE values.
ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_date_order;
ALTER TABLE public.events ALTER COLUMN best_known_start_date TYPE TEXT USING best_known_start_date::text;
ALTER TABLE public.events ALTER COLUMN best_known_end_date TYPE TEXT USING best_known_end_date::text;
CREATE TABLE IF NOT EXISTS public.event_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES public.events(id) ON DELETE RESTRICT,
    occurrence_name TEXT,
    event_start DATE,
    event_end DATE,
    occurrence_status TEXT,
    occurrence_contact_info TEXT,
    next_action_status TEXT,
    next_action TEXT,
    om_grade TEXT,
    occurrence_notes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    favorite BOOLEAN NOT NULL DEFAULT FALSE,
    source_main_event_id BIGINT REFERENCES public.main_events(id) ON DELETE SET NULL UNIQUE,
    source_spreadsheet_id TEXT,
    source_sheet_name TEXT,
    source_row INTEGER,
    sheet_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (event_end IS NULL OR event_start IS NULL OR event_end >= event_start),
    UNIQUE (source_spreadsheet_id, source_sheet_name, source_row)
);
ALTER TABLE public.event_occurrences ADD COLUMN IF NOT EXISTS next_action_status TEXT;
ALTER TABLE public.event_occurrences ADD COLUMN IF NOT EXISTS occurrence_name TEXT;
ALTER TABLE public.event_occurrences ADD COLUMN IF NOT EXISTS favorite BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.event_occurrences DROP COLUMN IF EXISTS start_time;
ALTER TABLE public.event_occurrences DROP COLUMN IF EXISTS end_time;
CREATE INDEX IF NOT EXISTS event_occurrences_event_id_idx ON public.event_occurrences(event_id);
CREATE INDEX IF NOT EXISTS event_occurrences_date_idx ON public.event_occurrences(event_start, active);
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.event_occurrences ENABLE ROW LEVEL SECURITY;
